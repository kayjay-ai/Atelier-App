// Runs after `expo export --platform web` (see "build:web") to make dist/ work on
// Cloudflare static assets (wrangler.jsonc at the repo root):
//
// 1. 404.html: Cloudflare's not_found_handling serves it; Expo names it +not-found.html.
// 2. Dynamic routes: Expo exports app/store/customer/[id].tsx once, as
//    store/customer/[id].html. Cloudflare can't serve that file under
//    /store/customer/<real id>: a rewrite to a bracketed name turns into a visible
//    redirect to /store/customer/%5Bid%5D, losing the id. So each [param].html gets
//    a bracket-free copy (__param.html), and _redirects rewrites every
//    /store/customer/<id> to it (status 200, so the URL in the browser stays as is).
import fs from 'fs'
import path from 'path'

const dist = path.resolve(process.argv[2] || 'dist')
if (!fs.existsSync(dist)) throw new Error(`web-postbuild: ${dist} not found; run expo export first`)

fs.copyFileSync(path.join(dist, '+not-found.html'), path.join(dist, '404.html'))

const rules = []
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name.startsWith('[')) throw new Error(`web-postbuild: dynamic folder ${full} isn't handled yet`)
      walk(full)
      continue
    }
    const m = /^\[(?:\.\.\.)?([A-Za-z0-9_]+)\]\.html$/.exec(entry.name)
    if (!m) continue
    const copy = `__${m[1]}`
    fs.copyFileSync(full, path.join(dir, `${copy}.html`))
    const urlDir = '/' + path.relative(dist, dir).split(path.sep).filter(Boolean).join('/')
    const base = urlDir === '/' ? '' : urlDir
    const splat = entry.name.startsWith('[...')
    rules.push(`${base}/${splat ? '*' : ':' + m[1]}  ${base}/${copy}  200`)
    if (!splat) rules.push(`${base}/:${m[1]}/  ${base}/${copy}  200`)
  }
}
walk(dist)

fs.writeFileSync(
  path.join(dist, '_redirects'),
  '# Generated by frontend/scripts/web-postbuild.mjs. Do not edit.\n' + rules.join('\n') + '\n',
)
console.log(`web-postbuild: 404.html + ${rules.length} rewrite rule(s)`)
